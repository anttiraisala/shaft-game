#!/usr/bin/env python3
"""Reference implementation of the floor layout generator.

Writes shared/test-vectors/floor_layout.csv. The Godot version and the
Commodore 64 version must both reproduce these values exactly.
"""

import sys
from pathlib import Path

TOTAL_FLOORS = 333
OUTPUT = Path(__file__).resolve().parent.parent / "shared" / "test-vectors" / "floor_layout.csv"


def next_state(state: int) -> int:
    """16-bit xorshift with shifts 7, 9, 8."""
    x = state & 0xFFFF
    x = (x ^ (x << 7)) & 0xFFFF
    x = x ^ (x >> 9)
    x = (x ^ (x << 8)) & 0xFFFF
    return x


def seed_for_floor(floor_number: int) -> int:
    seed = (floor_number * 40503 + 1) & 0xFFFF
    return seed if seed != 0 else 1


def layout_for_floor(floor_number: int) -> tuple[int, int, int, int, int, int, int]:
    seed = seed_for_floor(floor_number)
    s1 = next_state(seed)
    s2 = next_state(s1)
    s3 = next_state(s2)
    on_left = 1 if (s1 & 1) == 0 else 0
    room_start = 80 if on_left else 840
    ledge_x = room_start + s2 % 361
    ledge_height = 80 + s3 % 31
    return seed, s1, s2, s3, on_left, ledge_x, ledge_height


def main() -> int:
    lines = [
        "# Test vectors for the floor layout generator.",
        "# Generated by tools/generate_test_vectors.py. Do not edit by hand.",
        "# Columns: floor,seed,state1,state2,state3,on_left,ledge_x,ledge_height",
    ]
    for floor_number in range(1, TOTAL_FLOORS + 1):
        values = layout_for_floor(floor_number)
        lines.append(",".join(str(v) for v in (floor_number, *values)))
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {TOTAL_FLOORS} rows to {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
